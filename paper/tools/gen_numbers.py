def pct(a: float, b: float) -> float:
    return 100.0 * (a / b - 1.0)


def has(r: dict, col: str) -> bool:
    return r.get(col) not in (None, "")


def short_pct(r: dict, fallback: str | None = None) -> float | None:
    """Single-draw short share in %, or None if only a multi-draw share is available."""
    if has(r, "frac_img_short"):
        return 100 * float(r["frac_img_short"])
    return 100 * float(r[fallback]) if fallback else None


def rel_is(r: dict) -> tuple[float, bool]:
    """(relative interval score, is_robust): primary image-median score first, then the older fallbacks."""
    if has(r, "rel_interval_score_imgmed"):
        return float(r["rel_interval_score_imgmed"]), True
    if has(r, "rel_interval_score_robust"):
        return float(r["rel_interval_score_robust"]), True
    return float(r["rel_interval_score"]), False


def summary(path: Path, **match) -> dict[str, dict] | None:
    if not path.exists():
        return None
    return {r["method"]: r for r in csv.DictReader(open(path)) if all(r[k] == v for k, v in match.items())}


def e17_conf() -> tuple[dict, dict] | None:
    """E17c (validity.csv, compare.csv) keyed by (source, k, arm) and (source, k, A, B, metric), or None."""
    v, c = E17_CONF / "validity.csv", E17_CONF / "compare.csv"
    if not (v.exists() and c.exists()):
        return None
    return ({(r["source"], r["k"], r["arm"]): r for r in csv.DictReader(open(v))},
            {(r["source"], r["k"], r["A"], r["B"], r["metric"]): r for r in csv.DictReader(open(c))})


def e17_source(ds: str, model: str, lay: str) -> str:
    return f"{ds}__{model}" + ("" if lay == "uniform" else f"__{lay}")


def e17_methods(conf, ds: str, model: str, lay: str, k: str) -> dict[str, dict]:
    """Per-method rows of one pair x layout x k: E17c means over splits, else the exploratory summary."""
    src = e17_source(ds, model, lay)
    if conf:
        return {arm: r for (s, kk, arm), r in conf[0].items() if s == src and kk == k}
    return {r["method"]: r for r in csv.DictReader(open(E17_DIR / src / "summary.csv"))
            if r["base"] == "S2-log" and r["k"] == k}


def e17_rows(conf) -> list[str]:
    out = ["%% E17 (Tab. 2): \\ESeventeen{layout}{k}{col}; col in local, dual, short, dW, bW, dIS, bIS.",
           "%% local/dual = image-averaged coverage of A-local (all k structured anchors) / A-dual; short = % images",
           "%% with single-draw coverage < 0.85, A-dual (pending until frac_img_short exists); dW/bW = % change in",
           "%% median rel. width of A-dual / A-dual-both vs A-dist-both; dIS/bIS = % change in rel. interval score",
           "%% (primary if available), A-dual / A-dual-both vs A-dist-both. Median over the six pairs; lo / hi = min / max.",
           "%% Source: " + ("confirmatory E17c (20 splits x 10 draws, results/e17_conf/_confirm)." if conf
                            else "exploratory results/e17_p20_g05 (3 splits x 2 draws).")]
    short_pending = False
    for lay in LAYOUTS:
        for k in ("50", "200"):
            vals = {c: [] for c in ("local", "dual", "short", "dW", "bW", "dIS", "bIS")}
            for ds, model in E17_PAIRS:
                rows = e17_methods(conf, ds, model, lay, k)
                g = lambda m, c: float(rows[m][c])  # noqa: E731
                vals["local"].append(g("A-local", "cov_image_mean"))
                vals["dual"].append(g("A-dual", "cov_image_mean"))
                vals["short"].append(short_pct(rows["A-dual"]))
                vals["dW"].append(pct(g("A-dual", "median_rel_width"), g("A-dist-both", "median_rel_width")))
                vals["bW"].append(pct(g("A-dual-both", "median_rel_width"), g("A-dist-both", "median_rel_width")))
                vals["dIS"].append(pct(rel_is(rows["A-dual"])[0], rel_is(rows["A-dist-both"])[0]))
                vals["bIS"].append(pct(rel_is(rows["A-dual-both"])[0], rel_is(rows["A-dist-both"])[0]))
            for c, v in vals.items():
                fmt = "%.3f" if c in ("local", "dual") else ("%.1f" if c == "short" else "%.0f")
                tex = lambda x: (fmt % x).lstrip("-" if float(fmt % x) == 0 else "").replace("-", "$-$")  # noqa: E731
                for suffix in ("", "lo", "hi"):
                    if None in v:
                        val = PENDING_CONF
                    else:
                        val = tex({"": statistics.median(v), "lo": min(v), "hi": max(v)}[suffix])
                    out.append(f"\\expandafter\\def\\csname e17/{lay}/{k}/{c}{suffix}\\endcsname{{{val}}}")
                if c == "short" and None in v:
                    short_pending = True
    out += ["%% true while any E17 short cell is pending (Supp. ranges table then prints one marker, not [lo, hi])",
            "\\newif\\ifESeventeenShortPending",
            "\\ESeventeenShortPendingtrue" if short_pending else "\\ESeventeenShortPendingfalse"]
    if conf:
        out += ["%% confirmatory: table cells without \\prelim",
                "\\renewcommand{\\ESeventeen}[3]{\\ifcsname e17/#1/#2/#3\\endcsname\\csname e17/#1/#2/#3\\endcsname"
                "\\else\\pending{?}\\fi}"]
    return out


def e17_spread(lay: str, k: str, method: str, min_share: float = 0.01) -> list[float]:
    """Per pair: coverage spread (points) across distance bins holding >= min_share of pixels, E17c dist_summary
    averaged over splits."""
    out = []
    for ds, model in E17_PAIRS:
        bins: dict[str, list[tuple[float, float]]] = {}
        for p in sorted((ROOT / "results" / "e17_conf").glob(f"{e17_source(ds, model, lay)}__seeds*/dist_summary.csv")):
            for r in csv.DictReader(open(p)):
                if r["k"] == k and r["method"] == method and r["base"] == "S2-log":
                    bins.setdefault(r["dist_bin"], []).append((float(r["cov_image_mean"]), float(r["frac_px"])))
        cov = [statistics.fmean(c for c, _ in v) for v in bins.values() if statistics.fmean(s for _, s in v) >= min_share]
        if cov:
            out.append(100 * (max(cov) - min(cov)))
    return out


def e17_conf_text(conf) -> list[str]:
    """Text numbers from E17c; \\providecommand + \\renewcommand override the hand-written [prelim] macros."""
    if not conf:
        return []
    val, cmp = conf
    cells = [(ds, m, lay, k) for lay in LAYOUTS for k in ("50", "200") for ds, m in E17_PAIRS]
    src = lambda ds, m, lay: e17_source(ds, m, lay)  # noqa: E731
    v = lambda c, arm, col: float(val[(src(*c[:3]), c[3], arm)][col])  # noqa: E731
    cm = lambda c, a, b, met: cmp[(src(*c[:3]), c[3], a, b, met)]  # noqa: E731
    claim = lambda c, a, b, met: cm(c, a, b, met)["claim"] == "True"  # noqa: E731
    rel = lambda c, a, b, met: float(cm(c, a, b, met)["rel_diff_pct"])  # noqa: E731
    IS, W = "rel_interval_score_imgmed", "median_rel_width"

    def mac(name, value):
        return f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}"

    def by_cell(f):
        return [statistics.median(f((ds, m, lay, k)) for ds, m in E17_PAIRS) for lay in LAYOUTS for k in ("50", "200")]

    dual_cov = [v(c, "A-dual", "cov_image_mean") for c in cells]
    dist_cov = [v(c, "A-dist-both", "cov_image_mean") for c in cells]
    width_gain = by_cell(lambda c: -pct(v(c, "A-dual", W), v(c, "A-dist-both", W)))
    gate = min(sum(rel((ds, m, lay, k), "A-dual", "A-dist-both", W) <= -10 and claim((ds, m, lay, k), "A-dual", "A-dist-both", W)
                   for ds, m in E17_PAIRS) for lay in LAYOUTS for k in ("50", "200"))
    is_wins = {a: sum(claim(c, a, "A-dist-both", IS) for c in cells) for a in ("A-dual", "A-dual-both")}
    is_loss = {a: [rel(c, a, "A-dist-both", IS) for c in cells if float(cm(c, a, "A-dist-both", IS)["ci_lo"]) > 0]
               for a in ("A-dual", "A-dual-both")}
    ur = [c for c in cells if c[2] in ("uniform", "rows")]
    clu = [c for c in cells if c[2] == "cluster"]
    dual_is_ur = [-rel(c, "A-dual", "A-dist-both", IS) for c in ur]
    dual_is_clu = [rel(c, "A-dual", "A-dist-both", IS) for c in clu]
    both_lose = [rel(c, "A-dual-both", "A-dist-both", IS) for c in cells if not claim(c, "A-dual-both", "A-dist-both", IS)]
    both_w_clu = [-rel(c, "A-dual-both", "A-dist-both", W) for c in clu]
    local_clu = [v(c, "A-local", "cov_image_mean") for c in clu]
    exact = sum(val[(src(*c[:3]), c[3], "A-dual")]["exact"] == "True" for c in cells)
    p10_k50 = [v(c, "A-dual", "cov_image_p10") for c in cells if c[3] == "50"]
    short = [100 * v(c, "A-dual", "frac_img_short") for c in cells]
    spread = {m: [statistics.median(e17_spread(lay, k, m)) for lay in LAYOUTS for k in ("50", "200")]
              for m in ("A-dual", "A-dual-both")}
    rmax_w = [rel(c, "A-dual-rmax", "A-dual", W) for c in cells]
    rmax_is = [rel(c, "A-dual-rmax", "A-dual", IS) for c in cells]
    rmax_cov = [v(c, "A-dual-rmax", "cov_image_mean") for c in cells]
    rmax_short = [100 * v(c, "A-dual-rmax", "frac_img_short") for c in cells]
    f0 = lambda x: "%.0f" % x  # noqa: E731
    return ["%% E17c text numbers: 6 pairs x 5 layouts x k in {50, 200} = 60 cells, 20 splits x 10 draws; claims by",
            "%% rule 2 (paired bootstrap CI below 0 and A valid). Ranges are min--max over cells unless noted.",
            mac("NumAllCells", len(cells)),
            mac("NumDualCovLo", "%.3f" % min(dual_cov)), mac("NumDualCovHi", "%.3f" % max(dual_cov)),
            mac("NumDualExactCells", exact),
            mac("NumDistBothCovLo", "%.3f" % min(dist_cov)), mac("NumDistBothCovHi", "%.3f" % max(dist_cov)),
            "% A-dual median-width gain over A-dist-both: median over pairs, range over the 10 layout x k cells",
            mac("NumDualWidthGainLo", f0(min(width_gain))), mac("NumDualWidthGainHi", f0(max(width_gain))),
            "% fewest pairs (of 6) per layout x k cell where A-dual is >= 10 % narrower with a rule-2 claim",
            mac("NumDualGatePairs", gate),
            "% cells (of 60) where A-dual / A-dual-both beat A-dist-both on the primary IS (rule 2)",
            mac("NumDualISWins", is_wins["A-dual"]), mac("NumDualBothISWins", is_wins["A-dual-both"]),
            "% cells where A-dist-both is better (CI above 0) and the largest such excess (%)",
            mac("NumDualISLosses", len(is_loss["A-dual"])), mac("NumDualISLoseMax", "%.0f" % max(is_loss["A-dual"])),
            mac("NumDualBothISLosses", len(is_loss["A-dual-both"])),
            "% A-dual IS gain under uniform and rows anchors (%, every cell); A-dual minus A-dist-both IS under cluster (%)",
            mac("NumDualISGainURLo", f0(min(dual_is_ur))), mac("NumDualISGainURHi", f0(max(dual_is_ur))),
            mac("NumDualISClusterLo", ("%.0f" % min(dual_is_clu)).replace("-", "$-$")),
            mac("NumDualISClusterHi", "+%.0f" % max(dual_is_clu)),
            "% A-dual-both: largest IS excess over A-dist-both among cells without a claim (%); width gain under cluster",
            mac("NumDualBothISLoseMax", "%.1f" % max(both_lose)),
            mac("NumDualBothClusterWidthLo", "%.1f" % min(both_w_clu)),
            mac("NumDualBothClusterWidthHi", "%.1f" % max(both_w_clu)),
            "% A-local coverage under clustered anchors, k in {50, 200}, range over pairs (the failure result)",
            mac("NumLocalClusterCovLo", "%.2f" % min(local_clu)), mac("NumLocalClusterCovHi", "%.2f" % max(local_clu)),
            "% A-dual p10 (one draw), mean over pairs and layouts at k = 50; single-draw short share, range over cells",
            mac("NumMeasPTenTwenty", "%.3f" % statistics.fmean(p10_k50)),
            mac("NumESeventeenShort", "%.1f--%.1f\\%%" % (min(short), max(short))),
            "% coverage spread (points) across distance bins holding >= 1 % of pixels: median over pairs, range over cells",
            mac("NumSpreadDualLo", "%.1f" % min(spread["A-dual"])), mac("NumSpreadDualHi", "%.1f" % max(spread["A-dual"])),
            mac("NumSpreadDualBothLo", "%.1f" % min(spread["A-dual-both"])),
            mac("NumSpreadDualBothHi", "%.1f" % max(spread["A-dual-both"])),
            "% r = n = 20 arm (A-dual-rmax) vs A-dual: % increase in median width and in IS; its coverage and short share",
            mac("NumRmaxWidthCostLo", f0(min(rmax_w))), mac("NumRmaxWidthCostHi", f0(max(rmax_w))),
            mac("NumRmaxISCostLo", f0(min(rmax_is))), mac("NumRmaxISCostHi", f0(max(rmax_is))),
            mac("NumRmaxCovLo", "%.3f" % min(rmax_cov)), mac("NumRmaxCovHi", "%.3f" % max(rmax_cov)),
            mac("NumRmaxShort", "%.1f--%.1f\\%%" % (min(rmax_short), max(rmax_short)))]


def e17_text() -> list[str]:
    """Single-draw A-dual short share for the text: NYU/KITTI at n = 20 and n = 40, ARKitScenes at n = 20."""
    ark = [("arkitscenes", "dav2-indoor-large"), ("arkitscenes", "unidepthv2-large")]

    def rng(base: Path, pairs) -> str:
        xs = []
        for lay in LAYOUTS:
            for ds, model in pairs:
                sub = "" if lay == "uniform" else f"__{lay}"
                rows = summary(base / f"{ds}__{model}{sub}" / "summary.csv", base="S2-log")
                if not rows:
                    return PENDING_CONF
                for k in ("50", "200"):
                    r = summary(base / f"{ds}__{model}{sub}" / "summary.csv", base="S2-log", k=k).get("A-dual")
                    x = short_pct(r) if r else None
                    if x is None:
                        return PENDING_CONF
                    xs.append(x)
        return f"\\prelim{{{min(xs):.1f}}}--\\prelim{{{max(xs):.1f}}}\\%"

    return ["%% E17 single-draw short share of A-dual (% images < 0.85, macro includes \\%), range over pairs, layouts and k;",
            "%% \\pending{confirmatory} until the summaries carry frac_img_short (theory: 17.6 % at n = 20, 13.0 % at n = 40).",
            f"\\newcommand{{\\NumESeventeenShort}}{{{rng(E17_DIR, E17_PAIRS)}}}",
            f"\\newcommand{{\\NumESeventeenShortForty}}{{{rng(ROOT / 'results' / 'e17_p40_g05', E17_PAIRS)}}}",
            f"\\newcommand{{\\NumArkShortOne}}{{{rng(E17_DIR, ark)}}}"]


def e19_key(r: dict) -> tuple:
    return r["pattern"], r["centre"], r["pred_source"], r["probe_source"], r["method"]


def e19_table() -> dict[tuple, dict]:
    """Confirmatory means over seeds where E19c ran the cell; exploratory rows (marked "explor") elsewhere."""
    t = {e19_key(r): {**r, "_src": "explor"} for r in csv.DictReader(open(E19_CSV))}
    conf: dict[tuple, list[dict]] = {}
    for p in E19_SEED_RUNS:
        if "e19_conf_s" in str(p):
            for r in csv.DictReader(open(p)):
                conf.setdefault(e19_key(r), []).append(r)
    for k, rs in conf.items():
        t[k] = {c: str(statistics.mean(float(r[c]) for r in rs)) for c in E19_MEAN_COLS if has(rs[0], c)}
        t[k].update(n=str(len(rs)), _src="conf")
    return t


def e19_rows(t: dict) -> list[str]:
    out = ["%% E19 (Tab. 3, Supp.): \\ENineteen{pattern}{centre}{anchor src}{probe src}{method}{col};",
           "%% col in cov (truth coverage, image mean), ptten (p10 of per-image coverage, one draw), short (% images",
           "%% < 0.85, one draw), wgt (median width / laser depth), is (rel. interval score: primary if the column",
           f"%% exists, else exploratory; then > {IS_BLOWUP} is a blow-up from a few pixels -> \\pending),",
           "%% uninf (% pixels with width > 10 y, only if frac_uninformative exists)."]
    uninf = any(has(r, "frac_uninformative") for r in t.values())
    explor = ["/".join(k) for k, r in sorted(t.items()) if r["_src"] == "explor"]
    if explor and len(explor) < len(t):
        out.append("%% exploratory (seeds 0-2; not in the confirmatory E19c): " + ", ".join(explor))
    for (pat, cen, ps, qs, meth), r in sorted(t.items()):
        key = f"e19/{pat}/{cen}/{ps}/{qs}/{meth}"
        isv, robust = rel_is(r)
        cells = {"cov": "%.3f" % float(r["cov_image_mean"]), "ptten": "%.3f" % float(r["cov_image_p10"]),
                 "short": "%.1f" % short_pct(r, "cond_short_frac"), "wgt": "%.3f" % float(r["median_width_over_gt"]),
                 "is": ("%.3f" % isv) if robust or isv < IS_BLOWUP else None}
        if uninf:
            cells["uninf"] = ("%.1f" % (100 * float(r["frac_uninformative"]))) if has(r, "frac_uninformative") \
                else "--"
        for c, v in cells.items():
            if v is None:
                out.append(f"\\expandafter\\def\\csname {key}/{c}\\endcsname{{\\pending{{primary IS}}}}"
                           f" % mean {isv:.3g}: blow-up")
            else:
                out.append(f"\\expandafter\\def\\csname {key}/{c}\\endcsname{{{v}}}")
    out += ["%% true when the E19 summary carries frac_uninformative (Supp. Tab. S2 then shows an Uninf. column)",
            "\\newif\\ifENineteenUninf", "\\ENineteenUninftrue" if uninf else "\\ENineteenUninffalse"]
    out.append("%% Per-seed mean-over-images rel. IS of the blow-up cells -- NOT for the paper (primary IS is the image median):")
    seeds = {}
    for p in E19_SEED_RUNS:
        for r in csv.DictReader(open(p)):
            seeds.setdefault((r["pattern"], r["centre"], r["pred_source"], r["probe_source"], r["method"]), []).append(
                float(r["rel_interval_score"]))
    for k, v in sorted(seeds.items()):
        if max(v) > IS_BLOWUP:
            out.append("%%   " + "/".join(k) + ": " + " / ".join("%.3g" % x for x in v))
    return out


def e19_text(t: dict) -> list[str]:
    def v(pat, cen, ps, qs, meth, col):
        r = t[(pat, cen, ps, qs, meth)]
        return {"cov": float(r["cov_image_mean"]), "p10": float(r["cov_image_p10"]),
                "short": short_pct(r, "cond_short_frac"), "wgt": float(r["median_width_over_gt"]),
                "is": rel_is(r)[0]}[col]

    cc = ("clean", "clean")
    u_dual = v("uniform", "unidepth", *cc, "A-dual", "is")
    omni_u = [v("uniform", "omnidc", *cc, m, "is") for m in ("split-CP", "A-dual", "A-dist-split")]
    gain_u = [100 * (1 - x / u_dual) for x in omni_u]
